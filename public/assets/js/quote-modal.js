/* Item-specific quote requests, in a modal.
 *
 * WHY THIS IS ITS OWN FILE
 * ------------------------
 * Two surfaces need it and they load different scripts: the homepage loads
 * main.js, product pages load product.js (which documents, at its head, why it
 * is deliberately not main.js). There is no module system on these pages, so a
 * shared behaviour has to be a shared <script> — the same shape chat.js already
 * uses to appear on both.
 *
 * WHY THE MARKUP LIVES HERE AND NOT IN THE PAGES
 * ----------------------------------------------
 * index.html is a static file; the product page is generated by src/pdp.js. The
 * same dialog written into both would drift the first time one was edited, and
 * the drift would be invisible until someone reported that the form behaved
 * differently depending on where they opened it. So the DOM is built once, from
 * here, on first open.
 *
 * WHAT IT TALKS TO
 * ----------------
 * POST /api/quote — unchanged, and shared with the page-bottom form. It already
 * validates every field server-side (validateQuote in src/index.js), is rate
 * limited through RL_QUOTE, mails the owner with Reply-To set to the customer,
 * and mails the customer an acknowledgement via ctx.waitUntil. There was no
 * reason to add an endpoint, and a second one would have been a second thing to
 * keep rate limited.
 *
 * The page-bottom form on the homepage stays: it is the #quote anchor target, it
 * takes file attachments, and it handles requests that are not about any one
 * product. This is the path for "I want THAT, but different", which previously
 * scrolled you away from the thing you were pointing at.
 */
(function () {
  'use strict';

  const ENDPOINT = '/api/quote';

  /* Mirrors validateQuote() in src/index.js. Duplicated rather than shared, for
     the same reason product.js duplicates the cart contract: there is no module
     system here. These checks are for UX — the server's copy is the one that
     decides, and it re-runs every one of them. */

  /* The same expression main.js uses, so the two quote forms on this site agree
     about what an email address is. It is deliberately a shade stricter than the
     server's isEmail() in src/lib.js, which allows a consecutive or trailing dot
     in the domain ("a@b..c", "a@b.c."). Those are the ONLY two shapes the two
     disagree on, and both would bounce if we mailed them, so the stricter side is
     the right one to fail on.
     What must never happen is the reverse — this accepting something the server
     rejects, which would show a valid-looking form and then a 400. It does not:
     every pattern the server refuses, this refuses too. */
  const EMAIL_RE = /^[^\s@]+@[^\s@.]+(\.[^\s@.]+)+$/;
  const MIN_DESC = 10;      // src/index.js: q.desc.length < 10
  const MAX_QTY = 1000;     // src/index.js clamps to this

  /* The main form asks for this with a select. Here it is not asked at all:
     someone who clicked "different colour or size" on a specific product has
     already told us what kind of thing it is, and making them pick it out of a
     dropdown again is precisely the friction this dialog exists to remove.
     `ref_item` carries which product it was, and the owner email shows it as an
     "About" row. */
  const TYPE = 'Variation of a listed item';

  let modal = null;
  let overlay = null;
  let lastFocus = null;

  const $ = (id) => document.getElementById(id);

  function build() {
    overlay = document.createElement('div');
    overlay.className = 'checkout-overlay';
    overlay.id = 'qmOverlay';
    overlay.hidden = true;

    modal = document.createElement('div');
    // Reuses the checkout shell, as the sign-in, settings and receipt dialogs all
    // already do — one modal style per page.
    modal.className = 'checkout-modal quote-modal';
    modal.id = 'qmModal';
    modal.setAttribute('role', 'dialog');
    modal.setAttribute('aria-modal', 'true');
    modal.setAttribute('aria-labelledby', 'qmTitle');
    modal.setAttribute('aria-hidden', 'true');
    modal.hidden = true;

    modal.innerHTML = [
      '<div class="checkout-head">',
      '  <h3 id="qmTitle">Ask for a quote</h3>',
      '  <button class="cart-close" id="qmClose" type="button" aria-label="Close">✕</button>',
      '</div>',
      '<form class="checkout-form" id="qmForm" novalidate>',
      '  <div class="qm-ref" id="qmRef" hidden>',
      '    <img id="qmRefImg" src="" alt="" />',
      '    <div class="qm-ref-text">',
      '      <strong id="qmRefName"></strong>',
      '      <span>Tell me what you’d like changed and I’ll price it.</span>',
      '    </div>',
      '  </div>',
      '  <div class="co-row">',
      '    <div class="co-field">',
      '      <label for="qmName">Name <span aria-hidden="true">*</span></label>',
      '      <input type="text" id="qmName" name="name" autocomplete="name" required />',
      '      <span class="field-error" id="qmNameError"></span>',
      '    </div>',
      '    <div class="co-field">',
      '      <label for="qmEmail">Email <span aria-hidden="true">*</span></label>',
      '      <input type="email" id="qmEmail" name="email" autocomplete="email"',
      '             inputmode="email" placeholder="you@example.com" required />',
      '      <span class="field-error" id="qmEmailError"></span>',
      '    </div>',
      '  </div>',
      '  <div class="co-row">',
      '    <div class="co-field">',
      '      <label for="qmPhone">Phone <span class="co-optional">(optional)</span></label>',
      '      <input type="tel" id="qmPhone" name="phone" autocomplete="tel" inputmode="tel" />',
      '      <span class="field-error" id="qmPhoneError"></span>',
      '    </div>',
      '    <div class="co-field">',
      '      <label for="qmQty">Quantity</label>',
      '      <input type="number" id="qmQty" name="qty" min="1" max="1000" step="1" value="1" />',
      '      <span class="field-error" id="qmQtyError"></span>',
      '    </div>',
      '  </div>',
      '  <div class="co-field">',
      '    <label for="qmDesc">What would you like? <span aria-hidden="true">*</span></label>',
      '    <textarea id="qmDesc" name="desc" rows="4" maxlength="3000"',
      '              placeholder="Colour, size, material, deadline — anything that changes the price."></textarea>',
      '    <span class="field-error" id="qmDescError"></span>',
      '  </div>',
      '  <p class="qm-banner" id="qmBanner" hidden></p>',
      '  <button type="submit" class="btn-primary co-submit" id="qmSubmit">Send request</button>',
      '  <p class="qm-foot">I’ll reply by email, usually within a few hours.</p>',
      '</form>',
      '<div class="qm-done" id="qmDone" hidden>',
      '  <div class="qm-done-tick" aria-hidden="true">✓</div>',
      '  <h4>Request sent</h4>',
      '  <p id="qmDoneText"></p>',
      '  <button type="button" class="btn-primary" id="qmDoneClose">Close</button>',
      '</div>',
    ].join('\n');

    document.body.append(overlay, modal);

    $('qmClose').addEventListener('click', close);
    $('qmDoneClose').addEventListener('click', close);
    overlay.addEventListener('click', close);
    $('qmForm').addEventListener('submit', submit);

    // Clear a field's error as soon as it is touched, so the form stops telling
    // someone about a problem they are in the middle of fixing.
    ['qmName', 'qmEmail', 'qmPhone', 'qmQty', 'qmDesc'].forEach((id) => {
      $(id).addEventListener('input', () => clearError(id));
    });

    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && modal && !modal.hidden) close();
    });

    // A modal that lets Tab wander behind it is a modal in name only.
    modal.addEventListener('keydown', trapTab);
  }

  function trapTab(e) {
    if (e.key !== 'Tab') return;
    const focusable = [...modal.querySelectorAll(
      'button, input, textarea, select, a[href]',
    )].filter((n) => !n.disabled && n.offsetParent !== null);
    if (!focusable.length) return;
    const first = focusable[0];
    const last = focusable[focusable.length - 1];
    if (e.shiftKey && document.activeElement === first) {
      e.preventDefault(); last.focus();
    } else if (!e.shiftKey && document.activeElement === last) {
      e.preventDefault(); first.focus();
    }
  }

  function setError(id, message) {
    const field = $(id);
    const slot = $(id + 'Error');
    field.classList.add('invalid');
    field.setAttribute('aria-invalid', 'true');
    slot.textContent = message;
    slot.classList.add('show');
  }

  function clearError(id) {
    const field = $(id);
    const slot = $(id + 'Error');
    field.classList.remove('invalid');
    field.removeAttribute('aria-invalid');
    slot.classList.remove('show');
  }

  function banner(message) {
    const b = $('qmBanner');
    b.textContent = message || '';
    b.hidden = !message;
  }

  function validate() {
    const errors = [];
    const v = (id) => $(id).value.trim();

    const name = v('qmName');
    if (!name) errors.push(['qmName', 'Please enter your name.']);
    else if (name.length < 2) errors.push(['qmName', 'That name looks too short.']);

    const email = v('qmEmail');
    if (!email) errors.push(['qmEmail', 'Please enter your email address.']);
    else if (!EMAIL_RE.test(email)) errors.push(['qmEmail', "That doesn't look like a valid email address."]);

    const phone = v('qmPhone');
    if (phone) {
      const digits = phone.replace(/\D/g, '');
      if (digits.length < 7 || digits.length > 15) {
        errors.push(['qmPhone', 'That phone number looks wrong.']);
      }
    }

    const qty = parseInt(v('qmQty'), 10);
    if (!Number.isFinite(qty) || qty < 1) errors.push(['qmQty', 'At least 1.']);
    else if (qty > MAX_QTY) errors.push(['qmQty', `At most ${MAX_QTY}.`]);

    const desc = v('qmDesc');
    if (!desc) errors.push(['qmDesc', 'Please tell me what you need.']);
    else if (desc.length < MIN_DESC) errors.push(['qmDesc', 'A little more detail, please.']);

    return errors;
  }

  async function submit(e) {
    e.preventDefault();
    banner('');
    ['qmName', 'qmEmail', 'qmPhone', 'qmQty', 'qmDesc'].forEach(clearError);

    const errors = validate();
    if (errors.length) {
      for (const [id, msg] of errors) setError(id, msg);
      $(errors[0][0]).focus();
      return;
    }

    const btn = $('qmSubmit');
    btn.disabled = true;
    const label = btn.textContent;
    btn.textContent = 'Sending…';

    try {
      const res = await fetch(ENDPOINT, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          name: $('qmName').value.trim(),
          email: $('qmEmail').value.trim(),
          phone: $('qmPhone').value.trim(),
          type: TYPE,
          qty: parseInt($('qmQty').value, 10) || 1,
          desc: $('qmDesc').value.trim(),
          ref_item: modal.dataset.ref || '',
        }),
      });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) {
        // The server names the first problem it found; showing that beats a
        // generic failure, and it is the only way a rate-limit message reaches
        // the person who tripped it.
        banner(data.error || "That didn't send. Please try again.");
        return;
      }
      $('qmForm').hidden = true;
      $('qmDoneText').textContent =
        `Thanks — I've got your request and I'll reply to ${$('qmEmail').value.trim()} shortly.`;
      $('qmDone').hidden = false;
      $('qmDoneClose').focus();
    } catch (err) {
      console.error('quote modal submit failed', err);
      banner('Network error. Please check your connection and try again.');
    } finally {
      btn.disabled = false;
      btn.textContent = label;
    }
  }

  function open(item) {
    if (!modal) build();
    const it = item || {};

    // Reset to a clean form: reopening after a success must not show the previous
    // "Request sent" panel, and reopening on a DIFFERENT product must not carry
    // the last one's description.
    $('qmForm').hidden = false;
    $('qmDone').hidden = true;
    $('qmForm').reset();
    $('qmQty').value = '1';
    banner('');
    ['qmName', 'qmEmail', 'qmPhone', 'qmQty', 'qmDesc'].forEach(clearError);

    const label = it.name || 'this piece';
    const ref = $('qmRef');
    if (it.name || it.image) {
      // textContent, never innerHTML: a product name is owner-editable text and
      // this is the one place it would be parsed as markup.
      $('qmRefName').textContent = label;
      const img = $('qmRefImg');
      // Callers pass the stored path, "assets/images/x.jpg", with no leading
      // slash — which resolves against the current directory. That is harmless on
      // the homepage and broken on /p/<slug>, where it would look for
      // /p/assets/images/x.jpg. Rooted here rather than at each call site so the
      // two surfaces cannot disagree, and left alone if it is already absolute.
      const src = it.image || '';
      img.src = !src || /^(https?:)?\/\//.test(src) || src.startsWith('/') ? src : '/' + src;
      img.alt = label;
      img.hidden = !it.image;
      ref.hidden = false;
    } else {
      ref.hidden = true;
    }

    // The exact string the page-bottom form has always sent, so the owner's email
    // reads identically whichever path the request came through.
    modal.dataset.ref = it.name
      ? 'Product: ' + label + (it.image ? ' (' + it.image + ')' : '')
      : '';

    lastFocus = document.activeElement;
    overlay.hidden = false;
    modal.hidden = false;
    modal.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';
    $('qmName').focus();
  }

  function close() {
    if (!modal || modal.hidden) return;
    modal.hidden = true;
    overlay.hidden = true;
    modal.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
    // Back to the button that opened it, so a keyboard user is not dumped at the
    // top of the document.
    if (lastFocus && document.contains(lastFocus)) lastFocus.focus();
    lastFocus = null;
  }

  window.openQuoteModal = open;
})();
